'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const fix = path.join(__dirname, 'records/p2-fix');
const cases = JSON.parse(fs.readFileSync(path.join(fix, 'inputs/cases.json'), 'utf8'));
cases.push(JSON.parse(fs.readFileSync(path.join(fix, 'inputs/line-end-case.json'), 'utf8')));
const checker = process.env.STATIC_CONFIG_BASELINE === '1' ? path.join(fix, 'inputs/before-check.cjs') : path.join(__dirname, 'check.cjs');
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
for (const item of cases) test(item.id, () => {
  const files = item.args.filter((_, i) => item.args[i - 1] === '--schema' || item.args[i - 1] === '--plan' || item.args[i - 2] === '--source');
  const before = files.map(file => hash(path.join(root, file)));
  const r = spawnSync(process.execPath, [checker, ...item.args], { cwd: root, encoding: 'utf8', timeout: 5000 });
  assert.ifError(r.error);
  const out = JSON.parse(r.stdout);
  if (process.env.STATIC_CONFIG_CAPTURE === '1') fs.writeFileSync(path.join(fix, `outputs/final-${item.id}.json`), r.stdout, { flag: 'wx' });
  assert.equal(r.status, out.exitCode, 'actual process exit matches JSON');
  assert.equal(out.executionAuthorization, 'NOT_GRANTED');
  assert.equal(out.startCondition, 'BLOCKED');
  assert.equal(out.realExperiment, 'NOT_RUN');
  assert.equal(out.conditionU, 'NOT_RUN');
  assert.equal(out.productionWorker, 'HOLD');
  assert.deepEqual(out.hypotheses, { H1: 'UNKNOWN', H2: 'UNKNOWN', H3: 'UNKNOWN', H4: 'PARTIAL' });
  assert.deepEqual(files.map(file => hash(path.join(root, file))), before, 'input bytes unchanged');
  const planFile = item.args[item.args.indexOf('--plan') + 1];
  assert.equal(hash(path.join(root, planFile)), item.planSha256, 'same saved plan for baseline and fixed checker');
  assert.equal(out.files.find(f => f.id === 'config').sha256, item.configSha256);
  assert.equal(out.reasons.some(r => r.code === 'HASH_MISMATCH'), false, 'parser is tested with correct declared source hash');
  assert.equal(out.documentStatus, item.expectedStatus);
  assert.equal(r.status, item.expectedExit);
  if (item.expectedCode) assert.ok(out.reasons.some(r => r.code === item.expectedCode), item.expectedCode);
  else assert.deepEqual(out.reasons, []);
});
